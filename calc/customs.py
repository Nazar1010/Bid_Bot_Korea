@dataclass
class CustomsResult:
    duty_rub: float
    duty_eur: float
    duty_rule: str
    util_rub: float
    util_rule: str
    fee_rub: float
    age_group: str
    note: str = ""

    @property
    def total(self) -> float:
        return self.duty_rub + self.util_rub + self.fee_rub


def age_group(age: float) -> str:
    if age < 3:
        return "до 3 лет"
    if age <= 5:
        return "3–5 лет"
    return "старше 5 лет"


def duty(value_eur: float, cc: int, age: float) -> tuple[float, str]:
    """Пошлина в евро + словесное правило."""
    if age < 3:
        for limit, pct, min_cc in UNDER_3:
            if value_eur <= limit:
                by_pct, by_cc = value_eur * pct, cc * min_cc
                if by_pct >= by_cc:
                    return by_pct, f"{int(pct * 100)}% стоимости"
                return by_cc, f"{min_cc} €/см³ (минимум)"
    table = FROM_3_TO_5 if age <= 5 else OVER_5
    for limit, per_cc in table:
        if cc <= limit:
            return cc * per_cc, f"{per_cc} €/см³"
    raise ValueError("cc")


def clearance_fee(value_rub: float) -> float:
    for limit, fee in CLEARANCE_FEE:
        if value_rub <= limit:
            return fee
    return CLEARANCE_FEE[-1][1]


def _vol_group(cc: int) -> str:
    if cc <= 2000:
        return "1-2"
    if cc <= 3000:
        return "2-3"
    if cc <= 3500:
        return "3-3.5"
    return ">3.5"


def util_fee(cc: int, hp: int | None, age: float, year: int) -> tuple[float, str]:
    """Утильсбор для физлица. hp=None — считаем по льготе и предупреждаем."""
    old = age >= 3
    year = 2027 if year >= 2027 else 2026
    group = _vol_group(cc)
    if (hp is None or hp <= 160) and cc <= 3000:
        rule = "льготный (личное пользование, ≤160 л.с.)"
        if hp is None:
            rule += " — мощность не указана"
        return (UTIL_PREF_OLD if old else UTIL_PREF_NEW), rule
    if hp is not None and hp <= 160:
        vals = UTIL_BIG_LOW_POWER[group].get(year) or UTIL_BIG_LOW_POWER[group][2026]
        return vals[1 if old else 0], f"объём >3 л — без льготы ({year})"
    for limit, by_year in UTIL_TABLE[group]:
        if hp <= limit:
            new, older = by_year[year]
            return (older if old else new), f"{hp} л.с., объём {group} л — по таблице {year} г."
    raise ValueError("hp")


def calc(price_krw: int, krw_rub: float, eur_rub: float, cc: int, age: float,
         hp: int | None, decl_year: int) -> CustomsResult:
    value_rub = price_krw * krw_rub
    value_eur = value_rub / eur_rub
    d_eur, d_rule = duty(value_eur, cc, age)
    u_rub, u_rule = util_fee(cc, hp, age, decl_year)
    return CustomsResult(
        duty_rub=d_eur * eur_rub, duty_eur=d_eur, duty_rule=d_rule,
        util_rub=u_rub, util_rule=u_rule, fee_rub=clearance_fee(value_rub),
        age_group=age_group(age),
    )
