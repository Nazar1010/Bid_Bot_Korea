_HANGUL = re.compile(r"[가-힣]")


def has_hangul(text) -> bool:
    return bool(text) and bool(_HANGUL.search(str(text)))


def lookup(table: dict, value, default=None):
    """Точный перевод; если нет — оригинал (или default)."""
    if value is None or value == "":
        return default
    v = str(value).strip()
    if v in table:
        return table[v]
    compact = v.replace(" ", "")
    for k, ru in table.items():
        if k.replace(" ", "") == compact:
            return ru
    return v if default is None else default


def translate_words(text, words) -> str:
    """Перевод по ключевым словам: заменяет известные корейские куски."""
    if not text:
        return ""
    out = str(text)
    for ko, ru in words:
        out = out.replace(ko, ru)
    return out


def translate_part(title) -> str:
    """'프론트 펜더(좌)' → 'переднее крыло (левая)'."""
    if not title:
        return "деталь"
    out = translate_words(title, PART_WORDS)
    def side(m):
        inner = m.group(1)
        parts = [p.strip() for p in re.split(r"[,/]", inner)]
        ru = [dict(SIDE_WORDS).get(p, p) for p in parts]
        return " (" + ", ".join(ru) + ")"
    out = re.sub(r"\s*\(([^)]*)\)", side, out)
    return out.strip()


def translate_inner(title) -> str:
    return translate_words(title, INNER_WORDS).strip() if title else ""


def region(value) -> str:
    if not value:
        return ""
    v = str(value)
    for ko, ru in REGIONS.items():
        if v.startswith(ko):
            return ru
    return v
